# 📅 Day 5 – Data Cleaning in Excel: Turning Raw Data into Reliable Insights

**Date:** August 3, 2026

## Introduction

Before creating dashboards or running analysis, data must be clean and organized. Today I focused on one of the most important stages of data analytics—**Data Cleaning in Microsoft Excel**.

I learned that even the best visualization or model can produce misleading results if the underlying data contains errors, duplicates, or missing values.

---

## What I Learned Today

### 1. Removing Duplicate Records

Duplicate entries can distort analysis and lead to incorrect conclusions.

**Excel Feature Used:**

* Data → Remove Duplicates

---

### 2. Handling Missing Values

Missing data can affect calculations and reports.

Common approaches:

* Fill missing values where appropriate
* Replace blanks with meaningful values
* Remove incomplete records when necessary

---

### 3. Cleaning Text Data

Raw datasets often contain inconsistent formatting.

Useful Excel functions:

* `TRIM()` – Removes extra spaces
* `UPPER()` – Converts text to uppercase
* `LOWER()` – Converts text to lowercase
* `PROPER()` – Capitalizes each word
* `SUBSTITUTE()` – Replaces unwanted text

---

### 4. Find & Replace

A quick way to standardize inconsistent values.

Example:

* "Maharastra" → "Maharashtra"
* "Male" / "male" → "Male"

---

### 5. Converting Data Types

Ensuring numbers, dates, and text are stored in the correct format makes calculations accurate.

Examples:

* Text to Number
* Proper Date Formatting
* Currency Formatting

---

### 6. Sorting and Filtering

Sorting and filtering help identify:

* Outliers
* Missing values
* Duplicate records
* Incorrect entries

---

## Key Takeaways

* Clean data leads to better decisions.
* Small data issues can create large analytical errors.
* Data cleaning is an essential part of every analytics workflow.
* Excel provides powerful built-in tools to prepare data efficiently.

